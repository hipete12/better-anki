// Type-in-the-answer flow: create a deck + note via the API, study it in the UI.
import { chromium } from "playwright-core";
import { homedir } from "node:os";
const [base, out, user, pass] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: `${homedir()}/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome` });
const page = await browser.newPage({ viewport: { width: 1100, height: 760 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
const login = await (await fetch(`${base}/api/auth/login`, { method: "POST", body: JSON.stringify({ username: user, password: pass, device: "typing-check" }) })).json();
const H = { authorization: `Bearer ${login.token}`, "content-type": "application/json" };
const deck = await (await fetch(`${base}/api/decks`, { method: "POST", headers: H, body: JSON.stringify({ name: "Typing" }) })).json();
const nts = await (await fetch(`${base}/api/notetypes`, { headers: H })).json();
const nt = nts.find((n) => n.name === "Basic (type in the answer)");
await fetch(`${base}/api/notes`, { method: "POST", headers: H, body: JSON.stringify({ notetypeId: nt.id, deckId: deck.id, fields: ["Capital of France?", "Paris"] }) });
await page.goto(base);
await page.getByLabel("Username").fill(user);
await page.locator("input[type=password]").fill(pass);
await page.getByRole("button", { name: /Sign in/ }).click();
await page.getByRole("heading", { name: "Decks" }).waitFor();
await page.goto(`${base}/study/${deck.id}`);
await page.getByRole("button", { name: /Show answer/ }).waitFor();
await page.waitForTimeout(500);
const frame = page.frameLocator("iframe");
await frame.locator("#typeans").fill("Pariss");
await page.screenshot({ path: `${out}/typing-q.png` });
await frame.locator("#typeans").press("Enter");
await page.getByRole("button", { name: /Good/ }).waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/typing-a.png` });
const html = await frame.locator("body").innerHTML();
console.log("compare shown:", html.includes("typeBad") && html.includes("typeGood"));
await fetch(`${base}/api/auth/logout`, { method: "POST", headers: H });
console.log("errors:", errors.length ? errors : "none");
await browser.close();
